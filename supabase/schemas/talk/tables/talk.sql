-- Room talk on a prediction: preset phrases people post, and one reaction
-- each. Free text can join later as another kind of post.

-- The phrases people can post, by stage of the prediction. Edited by hand in
-- the SQL editor when the season changes: switch old ones off (active =
-- false) rather than deleting them, so earlier posts keep their text.
create table if not exists public.talk_phrases (
  id smallint generated by default as identity primary key,
  -- open: picks are open · locked: waiting for the result · result: revealed
  -- · void: no result or cancelled
  stage text not null check (stage in ('open', 'locked', 'result', 'void')),
  -- Who sees it in the sheet once revealed: everyone, or only those who
  -- called it / missed it.
  audience text not null default 'any' check (audience in ('any', 'winner', 'loser')),
  text text not null check (char_length(text) between 1 and 40),
  active boolean not null default true,
  sort_order smallint not null default 0,
  created_at timestamptz not null default now()
);

-- One reaction per person per prediction.
create table if not exists public.prediction_reactions (
  prediction_id uuid not null references public.predictions(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  -- Copied from the prediction so realtime can filter by room.
  room_id uuid not null references public.rooms(id) on delete cascade,
  reaction text not null check (reaction in ('laugh', 'wow', 'cry', 'angry', 'meh', 'fire')),
  created_at timestamptz not null default now(),
  primary key (prediction_id, player_id)
);
create index if not exists idx_prediction_reactions_room on public.prediction_reactions(room_id);

-- What people post to a prediction's room talk. Only preset phrases for now
-- (kind 'phrase'); up to 3 each per prediction, each phrase once.
create table if not exists public.prediction_posts (
  id uuid primary key default gen_random_uuid(),
  prediction_id uuid not null references public.predictions(id) on delete cascade,
  room_id uuid not null references public.rooms(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  kind text not null default 'phrase' check (kind in ('phrase')),
  phrase_id smallint references public.talk_phrases(id),
  -- The wall clock, so posts in one transaction still sort in order.
  created_at timestamptz not null default clock_timestamp(),
  constraint prediction_posts_phrase_check check (kind <> 'phrase' or phrase_id is not null)
);
create index if not exists idx_prediction_posts_prediction on public.prediction_posts(prediction_id, created_at desc);
create index if not exists idx_prediction_posts_room on public.prediction_posts(room_id);
create unique index if not exists uq_prediction_posts_phrase_once
  on public.prediction_posts(prediction_id, player_id, phrase_id)
  where kind = 'phrase';
