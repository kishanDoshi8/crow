-- Migration: room_talk
-- Description: Reactions and preset phrases on predictions ("Room talk").
--   One reaction per person per prediction (laugh, wow, cry, angry, meh,
--   fire); up to 3 preset phrases per person per prediction, each once.
--   Phrases live in talk_phrases, edited by hand when the season changes.
--   The room history cards gain the top reactions and the post count.
-- ============================================================


-- talk/tables/talk
-- Room talk on a prediction: preset phrases people post, and one reaction
-- each. Free text can join later as another kind of post.

-- The phrases people can post, by stage of the prediction. Edited by hand in
-- the SQL editor when the season changes: switch old ones off (active =
-- false) rather than deleting them, so earlier posts keep their text.
create table if not exists public.talk_phrases (
  id smallint generated by default as identity primary key,
  -- open: picks are open · locked: waiting for the result · result: revealed
  -- · void: no result or cancelled
  stage text not null check (stage in ('open', 'locked', 'result', 'void')),
  -- Who sees it in the sheet once revealed: everyone, or only those who
  -- called it / missed it.
  audience text not null default 'any' check (audience in ('any', 'winner', 'loser')),
  text text not null check (char_length(text) between 1 and 40),
  active boolean not null default true,
  sort_order smallint not null default 0,
  created_at timestamptz not null default now()
);

-- One reaction per person per prediction.
create table if not exists public.prediction_reactions (
  prediction_id uuid not null references public.predictions(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  -- Copied from the prediction so realtime can filter by room.
  room_id uuid not null references public.rooms(id) on delete cascade,
  reaction text not null check (reaction in ('laugh', 'wow', 'cry', 'angry', 'meh', 'fire')),
  created_at timestamptz not null default now(),
  primary key (prediction_id, player_id)
);
create index if not exists idx_prediction_reactions_room on public.prediction_reactions(room_id);

-- What people post to a prediction's room talk. Only preset phrases for now
-- (kind 'phrase'); up to 3 each per prediction, each phrase once.
create table if not exists public.prediction_posts (
  id uuid primary key default gen_random_uuid(),
  prediction_id uuid not null references public.predictions(id) on delete cascade,
  room_id uuid not null references public.rooms(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  kind text not null default 'phrase' check (kind in ('phrase')),
  phrase_id smallint references public.talk_phrases(id),
  -- The wall clock, so posts in one transaction still sort in order.
  created_at timestamptz not null default clock_timestamp(),
  constraint prediction_posts_phrase_check check (kind <> 'phrase' or phrase_id is not null)
);
create index if not exists idx_prediction_posts_prediction on public.prediction_posts(prediction_id, created_at desc);
create index if not exists idx_prediction_posts_room on public.prediction_posts(room_id);
create unique index if not exists uq_prediction_posts_phrase_once
  on public.prediction_posts(prediction_id, player_id, phrase_id)
  where kind = 'phrase';

-- talk/policies/talk_policies
-- Phrases are read through get_prediction_talk only.
alter table public.talk_phrases enable row level security;
revoke all on public.talk_phrases from anon, authenticated;

-- Members can read their room's reactions and posts (realtime needs this to
-- deliver changes); all writes go through the talk RPCs.
alter table public.prediction_reactions enable row level security;
revoke all on public.prediction_reactions from anon, authenticated;
drop policy if exists "prediction_reactions_select" on public.prediction_reactions;
create policy "prediction_reactions_select" on public.prediction_reactions
  for select to authenticated using (private.is_room_member(room_id));
grant select on public.prediction_reactions to authenticated;

alter table public.prediction_posts enable row level security;
revoke all on public.prediction_posts from anon, authenticated;
drop policy if exists "prediction_posts_select" on public.prediction_posts;
create policy "prediction_posts_select" on public.prediction_posts
  for select to authenticated using (private.is_room_member(room_id));
grant select on public.prediction_posts to authenticated;

-- talk/functions/prediction_talk
-- Which set of phrases fits a prediction right now.
create or replace function private.talk_stage(p_status text)
returns text
language sql
immutable
set search_path = public, private
as $$
  select case p_status
    when 'draft' then 'open'
    when 'locked' then 'locked'
    when 'revealed' then 'result'
    else 'void'
  end;
$$;

-- Everything the Room talk section shows for one prediction: reaction counts
-- and the caller's own, the posts (newest first), and the phrases the caller
-- can post now: the stage's phrases for everyone, plus those for people who
-- called it or missed it once it's revealed.
create or replace function public.get_prediction_talk(
  p_prediction_id uuid
)
returns json
language plpgsql
stable
security definer
set search_path = public, private
as $$
declare
  v_player_id uuid;
  v_prediction public.predictions%rowtype;
  v_stage text;
  v_audience text;
  v_my_option uuid;
begin
  v_player_id := private.get_player_id_from_auth();

  select * into v_prediction from public.predictions where id = p_prediction_id;
  if not found or not private.is_room_member(v_prediction.room_id) then
    raise exception 'Prediction not found' using errcode = 'P0002';
  end if;

  v_stage := private.talk_stage(v_prediction.status);

  select b.option_id into v_my_option
  from public.bets b
  where b.prediction_id = p_prediction_id
    and b.player_id = v_player_id;

  v_audience := case
    when v_prediction.status <> 'revealed' or v_my_option is null then null
    when v_my_option = v_prediction.winning_option_id then 'winner'
    else 'loser'
  end;

  return json_build_object(
    'stage', v_stage,
    'audience', v_audience,
    'post_limit', 3,
    'my_reaction', (
      select r.reaction from public.prediction_reactions r
      where r.prediction_id = p_prediction_id and r.player_id = v_player_id
    ),
    'reactions', coalesce((
      select json_agg(json_build_object('reaction', t.reaction, 'count', t.n) order by t.n desc, t.reaction)
      from (
        select r.reaction, count(*)::int as n
        from public.prediction_reactions r
        where r.prediction_id = p_prediction_id
        group by r.reaction
      ) t
    ), '[]'::json),
    'my_post_count', (
      select count(*)::int from public.prediction_posts p
      where p.prediction_id = p_prediction_id and p.player_id = v_player_id
    ),
    'posts', coalesce((
      select json_agg(json_build_object(
        'id', p.id,
        'player_id', p.player_id,
        'username', pl.username,
        'kind', p.kind,
        'text', ph.text,
        'created_at', p.created_at
      ) order by p.created_at desc, p.id desc)
      from public.prediction_posts p
      join public.players pl on pl.id = p.player_id
      left join public.talk_phrases ph on ph.id = p.phrase_id
      where p.prediction_id = p_prediction_id
    ), '[]'::json),
    'phrases', coalesce((
      select json_agg(json_build_object(
        'id', ph.id,
        'text', ph.text,
        'audience', ph.audience,
        'posted', exists (
          select 1 from public.prediction_posts p
          where p.prediction_id = p_prediction_id
            and p.player_id = v_player_id
            and p.phrase_id = ph.id
        )
      ) order by (ph.audience = 'any'), ph.sort_order, ph.id)
      from public.talk_phrases ph
      where ph.active
        and ph.stage = v_stage
        and (ph.audience = 'any' or ph.audience = v_audience)
    ), '[]'::json)
  );
end;
$$;

-- React to a prediction, switch reaction, or take it back (null).
create or replace function public.set_prediction_reaction(
  p_prediction_id uuid,
  p_reaction text default null
)
returns json
language plpgsql
security definer
set search_path = public, private
as $$
declare
  v_player_id uuid;
  v_room_id uuid;
  v_reaction text := nullif(trim(coalesce(p_reaction, '')), '');
begin
  v_player_id := private.get_player_id_from_auth();

  select room_id into v_room_id from public.predictions where id = p_prediction_id;
  if v_room_id is null or not private.is_room_member(v_room_id) then
    raise exception 'Prediction not found' using errcode = 'P0002';
  end if;

  if v_reaction is null then
    delete from public.prediction_reactions
    where prediction_id = p_prediction_id and player_id = v_player_id;
  else
    if v_reaction not in ('laugh', 'wow', 'cry', 'angry', 'meh', 'fire') then
      raise exception 'Unknown reaction' using errcode = 'P0001';
    end if;
    insert into public.prediction_reactions (prediction_id, player_id, room_id, reaction)
    values (p_prediction_id, v_player_id, v_room_id, v_reaction)
    on conflict (prediction_id, player_id)
    do update set reaction = excluded.reaction, created_at = now();
  end if;

  return json_build_object('reaction', v_reaction);
end;
$$;

-- Post a preset phrase to a prediction's room talk: one that fits its stage
-- (and the caller's result), each phrase once, up to 3 per person.
create or replace function public.post_prediction_phrase(
  p_prediction_id uuid,
  p_phrase_id smallint
)
returns json
language plpgsql
security definer
set search_path = public, private
as $$
declare
  v_player_id uuid;
  v_prediction public.predictions%rowtype;
  v_phrase public.talk_phrases%rowtype;
  v_my_option uuid;
  v_audience text;
  v_post public.prediction_posts%rowtype;
begin
  v_player_id := private.get_player_id_from_auth();

  select * into v_prediction from public.predictions where id = p_prediction_id;
  if not found or not private.is_room_member(v_prediction.room_id) then
    raise exception 'Prediction not found' using errcode = 'P0002';
  end if;

  select * into v_phrase from public.talk_phrases where id = p_phrase_id and active;
  if not found or v_phrase.stage <> private.talk_stage(v_prediction.status) then
    raise exception 'That phrase isn''t available now' using errcode = 'P0001';
  end if;

  if v_phrase.audience <> 'any' then
    select b.option_id into v_my_option
    from public.bets b
    where b.prediction_id = p_prediction_id and b.player_id = v_player_id;

    v_audience := case
      when v_prediction.status <> 'revealed' or v_my_option is null then null
      when v_my_option = v_prediction.winning_option_id then 'winner'
      else 'loser'
    end;

    if v_audience is distinct from v_phrase.audience then
      raise exception 'That phrase isn''t available now' using errcode = 'P0001';
    end if;
  end if;

  -- One post at a time per person and prediction, so the limit holds.
  perform pg_advisory_xact_lock(hashtextextended(p_prediction_id::text || v_player_id::text, 0));

  if (
    select count(*) from public.prediction_posts
    where prediction_id = p_prediction_id and player_id = v_player_id
  ) >= 3 then
    raise exception 'You''ve used your 3 phrases on this prediction' using errcode = 'P0001';
  end if;

  if exists (
    select 1 from public.prediction_posts
    where prediction_id = p_prediction_id
      and player_id = v_player_id
      and phrase_id = p_phrase_id
  ) then
    raise exception 'You''ve already said that one' using errcode = 'P0001';
  end if;

  insert into public.prediction_posts (prediction_id, room_id, player_id, kind, phrase_id)
  values (p_prediction_id, v_prediction.room_id, v_player_id, 'phrase', p_phrase_id)
  returning * into v_post;

  return json_build_object(
    'id', v_post.id,
    'text', v_phrase.text,
    'created_at', v_post.created_at
  );
end;
$$;

-- stats/functions/get_room_prediction_history
create or replace function public.get_room_prediction_history(
  p_room_id uuid,
  p_limit   int default 20,
  p_cursor_created_at timestamptz default null,
  p_cursor_id uuid default null,
  p_search text default null,
  p_filter text default 'all',
  p_series_id uuid default null
)
returns json
language plpgsql
security definer
set search_path = public, private
as $$
declare
  v_caller_id uuid;
  v_is_member boolean;
  v_result    json;
  v_filter text;
  v_search text;
begin
  v_caller_id := private.get_player_id_from_auth();
  if v_caller_id is null then
    raise exception 'Not authenticated' using errcode = 'P0004';
  end if;

  select exists(
    select 1 from public.room_members
    where room_id = p_room_id and player_id = v_caller_id
  ) into v_is_member;

  if not v_is_member then
    raise exception 'You are not a member of this room' using errcode = 'P0011';
  end if;

  p_limit  := greatest(1, least(p_limit, 100));
  v_filter := coalesce(nullif(lower(trim(p_filter)), ''), 'all');
  v_search := nullif(trim(p_search), '');

  /*
    Cursor pagination uses (created_at, id) so ordering is deterministic even when
    multiple predictions share the same created_at timestamp.
  */
  with fetched as (
    select
      pred.id             as prediction_id,
      pred.title,
      pred.status,
      pred.no_result_reason,
      pred.resolved_at,
      pred.created_at,
      pred.winning_option_id,
      pred.series_id,
      pred.series_prediction_number,
      s.title as series_title,
      user_bet.option_id  as selected_option_id,
      -- The caller's own stake and payout, for "you won / lost" on each card.
      user_bet.amount     as my_bet_amount,
      user_bet.payout     as my_payout,
      selected_opt.label  as selected_option_label,
      creator.username    as creator_username,
      resolver.username   as resolver_username,
      winning_opt.label   as winning_option_label,
      (
        select coalesce(sum(po.total_bet), 0)
        from public.prediction_options po
        where po.prediction_id = pred.id
      ) as total_pool,
      coalesce(bs.participant_count, 0) as participant_count,
      coalesce(bs.participant_count, 0) as total_bets,
      coalesce(bs.winner_count, 0) as winner_count,
      coalesce(bs.total_paid_to_winners, 0) as total_paid_to_winners,
      coalesce(bs.biggest_payout, 0) as biggest_payout,
      -- Room talk on the card: the top three reactions, the caller's own,
      -- and how many phrases were posted.
      (
        select json_agg(json_build_object('reaction', tr.reaction, 'count', tr.n) order by tr.n desc, tr.reaction)
        from (
          select r.reaction, count(*)::int as n
          from public.prediction_reactions r
          where r.prediction_id = pred.id
          group by r.reaction
          order by count(*) desc, r.reaction
          limit 3
        ) tr
      ) as top_reactions,
      (
        select r.reaction from public.prediction_reactions r
        where r.prediction_id = pred.id and r.player_id = v_caller_id
      ) as my_reaction,
      (
        select count(*)::int from public.prediction_posts pp
        where pp.prediction_id = pred.id
      ) as post_count,
      (
        select json_agg(
          json_build_object(
            'id',            po2.id,
            'label',         po2.label,
            'total_bet',     po2.total_bet,
            'display_order', po2.display_order
          ) order by po2.display_order
        )
        from public.prediction_options po2
        where po2.prediction_id = pred.id
      ) as options
    from public.predictions pred
    left join public.series s on s.id = pred.series_id
    join public.players creator on creator.id = pred.created_by
    left join public.players resolver on resolver.id = pred.resolved_by
    left join public.prediction_options winning_opt
      on winning_opt.id = pred.winning_option_id
    left join public.bets user_bet
      on user_bet.prediction_id = pred.id
      and user_bet.player_id = v_caller_id
    left join public.prediction_options selected_opt
      on selected_opt.id = user_bet.option_id
    left join (
      select
        b.prediction_id,
        count(*) as participant_count,
        count(*) filter (
          where pred2.status = 'revealed'
            and b.option_id = pred2.winning_option_id
        ) as winner_count,
        sum(
          case
            when pred2.status = 'revealed'
              then greatest(coalesce(b.payout, 0) - b.amount, 0)
            else 0
          end
        ) as total_paid_to_winners,
        max(
          case
            when pred2.status = 'revealed'
              then greatest(coalesce(b.payout, 0) - b.amount, 0)
            else 0
          end
        ) as biggest_payout
      from public.bets b
      join public.predictions pred2 on pred2.id = b.prediction_id
      where pred2.room_id = p_room_id
        and pred2.status in ('revealed', 'cancelled', 'no_result')
      group by b.prediction_id
    ) bs on bs.prediction_id = pred.id
    where pred.room_id = p_room_id
      and pred.status in ('revealed', 'cancelled', 'no_result')
      and (p_series_id is null or pred.series_id = p_series_id)
      and (
        p_cursor_created_at is null
        or p_cursor_id is null
        or (pred.created_at, pred.id) < (p_cursor_created_at, p_cursor_id)
      )
      and (
        v_search is null
        or coalesce(pred.title, '') ilike '%' || v_search || '%'
      )
      and case v_filter
        when 'wins' then (
          pred.status = 'revealed'
          and user_bet.option_id is not null
          and user_bet.option_id = pred.winning_option_id
        )
        when 'losses' then (
          pred.status = 'revealed'
          and user_bet.option_id is not null
          and user_bet.option_id <> pred.winning_option_id
        )
        when 'my_bets' then user_bet.option_id is not null
        else true
      end
    order by pred.created_at desc, pred.id desc
    limit p_limit + 1
  ),
  items as (
    select *
    from fetched
    order by created_at desc, prediction_id desc
    limit p_limit
  ),
  pagination as (
    select count(*) > p_limit as has_more
    from fetched
  ),
  tail_item as (
    select i.created_at, i.prediction_id
    from items i
    order by i.created_at asc, i.prediction_id asc
    limit 1
  )
  select json_build_object(
    'items', coalesce((select json_agg(i order by i.created_at desc, i.prediction_id desc) from items i), '[]'::json),
    'next_cursor_created_at', case when p.has_more then t.created_at else null end,
    'next_cursor_id', case when p.has_more then t.prediction_id else null end,
    'has_more', p.has_more
  )
  into v_result
  from pagination p
  left join tail_item t on true;

  return coalesce(
    v_result,
    json_build_object(
      'items', '[]'::json,
      'next_cursor_created_at', null,
      'next_cursor_id', null,
      'has_more', false
    )
  );
end;
$$;

